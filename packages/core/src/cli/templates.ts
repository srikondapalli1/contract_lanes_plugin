export const exampleContract = `import { z } from "zod";

export const VERSION = "1.0.0";

/** A task the "server" lane publishes and the "app" lane renders. Edit freely until \`lanes lock\`. */
export const schema = z.object({
  id: z.string().min(1),
  title: z.string().min(1).max(120),
  done: z.boolean(),
  priority: z.int().min(1).max(5),
  tags: z.array(z.string().min(1)).max(10).optional(),
});

export type Example = z.infer<typeof schema>;
`;

