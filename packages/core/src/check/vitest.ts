// Runs the engine file + consumer tests in ONE vitest process with lanes' generated config.
import { existsSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { cachePath, readJson, rel, toPosix, writeText } from "../util/fs.ts";
import { run } from "../util/git.ts";
import type { EnginePlan } from "./engine.ts";

export function resolveVitest(root: string): string | undefined {
  try {
    const req = createRequire(join(root, "package.json"));
    const pkgFile = req.resolve("vitest/package.json");
    const pkg = req(pkgFile);
    const bin = typeof pkg.bin === "string" ? pkg.bin : pkg.bin?.vitest;
    return join(dirname(pkgFile), bin ?? "vitest.mjs");
  } catch { return undefined; }
}

/** Where the bundled test/engine module lives (sibling of the running CLI bundle). */
export function engineModule(): string {
  const here = dirname(fileURLToPath(import.meta.url));
  for (const p of [join(here, "test.mjs"), join(here, "..", "test.mjs"), join(here, "..", "test", "index.ts")]) if (existsSync(p)) return p;
  return join(here, "test.mjs");
}

const USER_CONFIGS = ["vitest.config.ts", "vitest.config.mts", "vitest.config.js", "vitest.config.mjs"];

/** Per-process file names, so concurrent checks in one checkout don't clobber each other. */
export const runFiles = (root: string) => {
  const id = `${process.pid}`;
  return { engine: `engine-${id}.lanes.mjs`, config: cachePath(root, `vitest-${id}.config.mjs`), out: cachePath(root, `engine-${id}.json`), json: cachePath(root, `vitest-${id}.json`) };
};

export function writeEngineFiles(root: string, plan: EnginePlan, contractFiles: Record<string, string>, handlerFiles: Record<string, string>, include: string[]) {
  const f = runFiles(root);
  const dir = cachePath(root, "");
  const imp = (file: string) => {
    const r = toPosix(relative(dir, join(root, file)));
    return JSON.stringify(r.startsWith(".") ? r : `./${r}`);
  };
  const map = (o: Record<string, string>) => `{\n${Object.entries(o).map(([k, f]) => `  ${JSON.stringify(k)}: () => import(${imp(f)}),`).join("\n")}\n}`;
  writeText(join(dir, f.engine), `// generated by lanes check; do not edit
import { test } from "vitest";
import * as z from "zod";
import { runEngine } from ${JSON.stringify(toPosix(engineModule()))};
const plan = ${JSON.stringify(plan)};
test("lanes engine", async () => {
  await runEngine({ z, plan, out: ${JSON.stringify(toPosix(f.out))}, load: ${map(contractFiles)}, handlers: ${map(handlerFiles)} });
}, 600000);
`);
  const user = USER_CONFIGS.find((f) => existsSync(join(root, f)));
  writeText(f.config, `// generated by lanes check; merges your vitest config, then pins include/reporters
${user ? `import user from ${imp(user)};\nconst base = typeof user === "function" ? await user({ command: "serve", mode: "test" }) : (user ?? {});` : "const base = {};"}
const t = base.test ?? {};
const deps = t.server?.deps ?? {};
const test = {
  ...t,
  include: ${JSON.stringify(include)},
  exclude: ["**/node_modules/**", "**/.git/**"],
  watch: false, passWithNoTests: true,
  coverage: { enabled: false },
  server: { ...(t.server ?? {}), deps: { ...deps, inline: deps.inline === true ? true : [...(deps.inline ?? []), /contract-lanes/] } },
};
delete test.projects; delete test.workspace; delete test.reporters; delete test.outputFile;
export default { ...base, root: ${JSON.stringify(toPosix(root))}, test };
`);
}

export interface VitestFile { file: string; status: string; message?: string; tests: { title: string; status: string; failureMessages: string[] }[] }

export function runVitest(root: string): { ok: boolean; error?: string; files: VitestFile[] } {
  const bin = resolveVitest(root);
  if (!bin) return { ok: false, error: "vitest is not installed in this project. Install the peers: npm i -D vitest zod contract-lanes", files: [] };
  const f = runFiles(root);
  const out = f.json;
  const r = run(process.execPath, [bin, "run", "--config", f.config, "--root", root, "--reporter=json", `--outputFile=${out}`], { cwd: root, env: { ...process.env, FORCE_COLOR: "0", CI: process.env.CI ?? "" } });
  const json = readJson(out);
  if (!json) return { ok: false, error: `vitest did not produce results (exit ${r.code}): ${(r.stderr || r.stdout).trim().split("\n").slice(-8).join(" | ")}`, files: [] };
  const files: VitestFile[] = (json.testResults ?? []).map((t: any) => ({
    file: rel(root, t.name), status: t.status, message: t.message || undefined,
    tests: (t.assertionResults ?? []).map((a: any) => ({ title: a.fullName ?? a.title, status: a.status, failureMessages: a.failureMessages ?? [] })),
  }));
  return { ok: true, files };
}
